'use client';

import { LIVERIES, LIVERY_COLOURS, keysOf } from '@/data/options';
import { paintHex, priceTag } from '@/engine';
import { Block, Cards, Note, Range, Swatches } from '@/components/config/controls';
import { useEvaluation } from '@/components/config/useEngine';
import { useBuild } from '@/store/build';

export function LiveryStep() {
  const b = useBuild((st) => st.build);
  const ev = useEvaluation();
  const shown = keysOf(LIVERIES).filter((k) => !LIVERIES[k].rg || LIVERIES[k].rg === b.region);
  return (
    <>
      <Block title="Pattern" em="livery">
        <Cards
          k="livery"
          items={shown.map((k) => ({
            v: k,
            n: LIVERIES[k].n,
            sub: priceTag(LIVERIES[k].p, b.region),
            rg: LIVERIES[k].rg,
            why: ev.available.livery?.[k]?.reason,
            pattern: {
              id: LIVERIES[k].id,
              a: paintHex(b),
              b: LIVERY_COLOURS[b.livCol].c,
              mode: 'liv',
              scale: b.livScale,
            },
          }))}
        />
      </Block>
      <Block title="Pattern colour" em="livCol">
        <Swatches
          k="livCol"
          items={keysOf(LIVERY_COLOURS).map((k) => ({
            v: k,
            n: LIVERY_COLOURS[k].n,
            c: LIVERY_COLOURS[k].c,
          }))}
        />
      </Block>
      <Block title="Scale" em="livScale">
        <Range k="livScale" min={0.6} max={1.8} step={0.05} label="Livery scale" />
      </Block>
      <Note>
        Patterns are generated by the paint shader from each panel&apos;s position, so they run cleanly across
        door gaps and stay sharp at any size.
      </Note>
    </>
  );
}
