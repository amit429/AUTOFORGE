const cache = new Map<BodyTypeId, BodyGeometry>();

/** Shared geometry helper for a body style (profiles are pure, so one instance per type). */
export function bodyGeometry(id: BodyTypeId) {
  let g = cache.get(id);
  if (!g) cache.set(id, (g = new BodyGeometry(BODY_SPECS[id])));
  return g;
}
